namespace Nasurino.SmartWallet.Entities;

/// <summary>
/// Типы финансовых транзакций в системе.
/// Определяет семантический тип операции для корректной обработки бизнес-логики
/// и расчёта балансов денежных хранилищ.
/// </summary>
public enum TransactionType
{
    /// <summary>
    /// Перевод денежных средств между двумя хранилищами.
    /// Пример: перевод с банковской карты на наличные.
    /// Баланс системы в целом не изменяется, деньги перемещаются между хранилищами.
    /// </summary>
    Transfer,

    /// <summary>
    /// Трата денежных средств из хранилища в категорию расходов.
    /// Пример: покупка продуктов из кошелька.
    /// Уменьшает баланс хранилища и увеличивает значение области трат.
    /// </summary>
    Expense,

    /// <summary>
    /// Корректировка баланса хранилища с уменьшением суммы.
    /// Пример: обнаружение ошибки в учёте или списание комиссии.
    /// Уменьшает баланс хранилища без привязки к категории расходов.
    /// </summary>
    StorageDecreaseAdjustment,

    /// <summary>
    /// Корректировка баланса хранилища с увеличением суммы.
    /// Пример: возврат ошибочно списанных средств или начисление бонусов.
    /// Увеличивает баланс хранилища без привязки к доходам извне.
    /// </summary>
    StorageIncreaseAdjustment,

    /// <summary>
    /// Корректировка баланса категории расходов с уменьшением суммы.
    /// Пример: возврат товара в магазин или отмена траты.
    /// Уменьшает значение области трат без изменения баланса хранилища.
    /// </summary>
    CategoryDecreaseAdjustment,

    /// <summary>
    /// Корректировка баланса категории расходов с увеличением суммы.
    /// Пример: дополнительные расходы по ранее оформленной покупке.
    /// Увеличивает значение области трат без изменения баланса хранилища.
    /// </summary>
    CategoryIncreaseAdjustment,

    /// <summary>
    /// Доход — поступление денежных средств извне системы в хранилище.
    /// Пример: получение зарплаты или подарка.
    /// Увеличивает баланс хранилища и общий баланс системы.
    /// </summary>
    Income,
    
    /// <summary>
    /// Для тестов
    /// </summary>
    ForTest
}